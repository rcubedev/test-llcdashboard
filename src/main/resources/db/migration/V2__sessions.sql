-- Spring Session's tables (from spring-session-jdbc's schema-postgresql.sql), where sign-ins are kept. They're named
-- DASHBOARD_SESSION so they can't clash with the auth app's SPRING_SESSION when both share a database.
-- Its own schema setup is off (spring.session.jdbc.initialize-schema: never) so Flyway alone changes the database.

CREATE TABLE DASHBOARD_SESSION (
	PRIMARY_ID CHAR(36) NOT NULL,
	SESSION_ID CHAR(36) NOT NULL,
	CREATION_TIME BIGINT NOT NULL,
	LAST_ACCESS_TIME BIGINT NOT NULL,
	MAX_INACTIVE_INTERVAL INT NOT NULL,
	EXPIRY_TIME BIGINT NOT NULL,
	PRINCIPAL_NAME VARCHAR(100),
	CONSTRAINT DASHBOARD_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX DASHBOARD_SESSION_IX1 ON DASHBOARD_SESSION (SESSION_ID);
CREATE INDEX DASHBOARD_SESSION_IX2 ON DASHBOARD_SESSION (EXPIRY_TIME);
CREATE INDEX DASHBOARD_SESSION_IX3 ON DASHBOARD_SESSION (PRINCIPAL_NAME);

CREATE TABLE DASHBOARD_SESSION_ATTRIBUTES (
	SESSION_PRIMARY_ID CHAR(36) NOT NULL,
	ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
	ATTRIBUTE_BYTES BYTEA NOT NULL,
	CONSTRAINT DASHBOARD_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
	CONSTRAINT DASHBOARD_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES DASHBOARD_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
